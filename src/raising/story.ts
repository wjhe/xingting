export function eligible(event: StoryEvent, state: GameState): boolean {
  const age=10+Math.floor(state.month/12), c=event.conditions;
  if (state.flags.includes(`event:${event.id}`) || age<(event.minAge??10) || age>(event.maxAge??18)) return false;
  if (event.dueMonth!==undefined && (event.dueMonth>state.month || event.dueMonth<state.storyStartMonth)) return false;
  if (!c) return true;
  return (!c.months || c.months.includes(state.month%12+1)) &&
    (!c.minStats || Object.entries(c.minStats).every(([key,value])=>state.stats[key as keyof Stats]>=value!)) &&
    state.stress>=(c.minStress??0) && state.stress<=(c.maxStress??100) && state.bond>=(c.minBond??0) &&
    (!c.activities || Object.entries(c.activities).every(([id,count])=>(state.activityCounts[id]??0)>=count)) &&
    (!c.flags || c.flags.every(f=>state.flags.includes(f))) && (!c.notFlags || c.notFlags.every(f=>!state.flags.includes(f))) &&
    (!c.outfit || state.outfit===c.outfit);
}

